#!/usr/bin/env python3
"""Render RloAudit JSON snapshots as a per-member review inventory (no upstream source copied)."""
import json
from pathlib import Path
import sys

if len(sys.argv) != 4:
    sys.exit('Usage: compare-rlo.py <old.json> <new.json> <report.md>')
old, new = (json.loads(Path(p).read_text()) for p in sys.argv[1:3])
a, b = old['members'], new['members']
same = sum(a[k] == b.get(k) for k in a)
changed = sum(a[k] != b[k] for k in a.keys() & b.keys())
added, removed = len(b.keys() - a.keys()), len(a.keys() - b.keys())
lines = [
    '# RLO ' + new['version'] + ' binary target inventory', '',
    'Generated by `tools/RloAudit` and `tools/compare-rlo.py` from official release DLLs. '
    'This is metadata and normalized method-body hashes, not decompiled source. '
    'The inventory includes indirect billing, codec and school consumers as well as exact patch targets. '
    'See [the review conclusions](../rlo-compatibility.md).', '',
    f"{old['version']}: `{old['sha256']}`. {new['version']}: `{new['sha256']}`.", '',
    f'{len(a)} prior entries: {same} unchanged, {changed} changed, {added} added, {removed} removed. '
    'Changed bodies require source review; this report does not approve a version by itself.', '',
    '| Type / member signature | Comparison | Current attributes / parameter names / normalized IL hash |',
    '| --- | --- | --- |',
]
for key in sorted(a.keys() | b.keys()):
    value = b.get(key)
    status = 'Unchanged' if a.get(key) == value else 'Added' if key not in a else 'Removed' if key not in b else 'Changed; see review'
    # Reflection uses a literal backtick in generic type names; double-backtick spans preserve it.
    lines.append('| ``' + key.replace('|', '\\|') + '`` | ' + status + ' | ``' + str(value).replace('|', '\\|') + '`` |')
Path(sys.argv[3]).write_text('\n'.join(lines) + '\n')
print(f'{same} unchanged, {changed} changed, {added} added, {removed} removed')
